function loadNextQuestion() {
    isAnswerChecked = false;
    selectedOptionBtn = null;
    actionBtn.textContent = "TEKSHIRISH";
    actionBtn.disabled = true;
    actionBtn.className = "btn-primary";
    footer.className = "footer";
    feedbackMsg.textContent = "";
    appContainer.classList.remove("shake");

    progressBar.style.width = `${(currentQuestionCount / totalQuestions) * 100}%`;

    if (currentQuestionCount >= totalQuestions) {
        currentPhase = 2;
        showPhaseTransition("BOMBA REJIM", "Ajoyib! Endi chap va o'ng ustundagi so'zlarni xatosiz bir-biriga ulang!");
        return;
    }

    currentWord = activeWords[currentQuestionCount];
    questionMode = Math.random() > 0.7 ? 'input' : 'mcq';

    if (questionMode === 'input') {
        document.getElementById("question-title").textContent = "Inglizchasini yozing!";
        mainWordEl.textContent = currentWord.uz;
        optionsGrid.style.display = "none";
        inputContainer.style.display = "flex";
        typeInput.value = "";
        typeInput.className = "";
        typeInput.focus();
    } else {
        document.getElementById("question-title").textContent = "Tarjimasi qanday?";
        inputContainer.style.display = "none";
        optionsGrid.style.display = "flex";

        const isEnToUz = Math.random() > 0.5;
        mainWordEl.textContent = isEnToUz ? currentWord.en : currentWord.uz;
        const correctTarget = isEnToUz ? currentWord.uz : currentWord.en;

        // pool for wrong options: prefer selectedUnitKey's array, otherwise use activeWords (merged books)
        const pool = (selectedUnitKey && database[selectedUnitKey]) ? database[selectedUnitKey] : activeWords;
        const wrongOptions = shuffle([...pool])
            .filter(w => w.en !== currentWord.en)
            .slice(0, 3)
            .map(w => isEnToUz ? w.uz : w.en);

        const allOptions = shuffle([correctTarget, ...wrongOptions]);

        optionsGrid.innerHTML = "";
        allOptions.forEach(opt => {
            const btn = document.createElement("button");
            btn.className = "option-card";
            btn.textContent = opt;
            btn.onclick = () => {
                if (isAnswerChecked) return;
                document.querySelectorAll(".option-card").forEach(el => el.classList.remove("selected"));
                btn.classList.add("selected");
                selectedOptionBtn = btn;
                actionBtn.disabled = false;
            };
            optionsGrid.appendChild(btn);
        });
    }
}

