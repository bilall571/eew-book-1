let autoRedirectTimer = null;

function showResults() {
    gameHeader.style.display = "none";
    switchView("result");

    let accuracy = Math.round((20 / (20 + mistakesCount)) * 100);
    if (accuracy > 100) accuracy = 100;

    document.getElementById("result-percent").textContent = accuracy + "%";
    document.getElementById("result-mistakes").textContent = "Xatolar soni: " + mistakesCount;

    let stars = "⭐";
    if (accuracy >= 92) stars = "⭐⭐⭐⭐⭐";
    else if (accuracy >= 78) stars = "⭐⭐⭐⭐";
    else if (accuracy >= 60) stars = "⭐⭐⭐";
    else if (accuracy >= 40) stars = "⭐⭐";

    document.getElementById("result-stars").textContent = stars;

    // XATO QILINGAN SO'ZLAR RO'YXATINI QURISH
    const failedContainer = document.getElementById("failed-words-container");
    failedContainer.innerHTML = ""; // Oldingisini tozalash

    if (failedWords.length > 0) {
        const title = document.createElement("h3");
        title.className = "failed-list-title";
        title.textContent = "Topa olmagan so'zlaringiz:";
        failedContainer.appendChild(title);

        const listBlock = document.createElement("div");
        listBlock.className = "failed-list";

        failedWords.forEach(word => {
            const item = document.createElement("div");
            item.className = "failed-item";
            item.innerHTML = `
                <span class="failed-en">${word.en}</span>
                <span class="failed-arrow">➔</span>
                <span class="failed-uz">${word.uz}</span>
            `;
            listBlock.appendChild(item);
        });
        failedContainer.appendChild(listBlock);
    }

    // AGAR XATO KO'P BO'LSA USER BEMALOL O'QIB OLIShI UCHUN AVTO-QAYTISHNI 10 SEKUND QILAMIZ.
    // AGAR XATO YO'Q BO'LSA 4 SEKUNDDA QAYTADI.
    const delayTime = failedWords.length > 0 ? 10000 : 4000;
    autoRedirectTimer = setTimeout(returnToDashboard, delayTime);

    document.getElementById("finish-game-btn").onclick = () => {
        clearTimeout(autoRedirectTimer);
        returnToDashboard();
    };
}

function returnToDashboard() {
    if (autoRedirectTimer) clearTimeout(autoRedirectTimer);
    gameHeader.style.display = "none";
    footer.style.display = "none";
    switchView("dashboard");
    buildDashboard();
}

