actionBtn.onclick = () => {
    if (!isAnswerChecked) {
        isAnswerChecked = true;
        let isCorrect = false;
        let correctTarget = "";

        if (questionMode === 'input') {
            const userAnswer = typeInput.value.trim().toLowerCase();
            correctTarget = currentWord.en.toLowerCase();
            isCorrect = (userAnswer === correctTarget);
            typeInput.classList.add(isCorrect ? "correct" : "wrong");
        } else {
            correctTarget = mainWordEl.textContent === currentWord.en ? currentWord.uz : currentWord.en;
            isCorrect = (selectedOptionBtn && selectedOptionBtn.textContent === correctTarget);
        }

        if (isCorrect) {
            if (selectedOptionBtn) selectedOptionBtn.classList.add("correct");
            footer.classList.add("correct-bg");
            actionBtn.classList.add("btn-correct");
            feedbackMsg.textContent = "✅ Ajoyib! To'g'ri topdingiz.";
            actionBtn.textContent = "DAVOM ETISH";
            currentQuestionCount++;
        } else {
            mistakesCount++;

            // XATO QILINGAN SO'ZNI RO'YXATGA QO'SHISH
            if (!failedWords.some(w => w.en === currentWord.en)) {
                failedWords.push(currentWord);
            }

            appContainer.classList.add("shake");
            if (selectedOptionBtn) selectedOptionBtn.classList.add("wrong");
            footer.classList.add("wrong-bg");
            actionBtn.classList.add("btn-wrong");
            feedbackMsg.textContent = `❌ Noto'g'ri! Aslida: ${correctTarget}`;
            actionBtn.textContent = "TUSHUNDIM";
            document.querySelectorAll(".option-card").forEach(b => { if(b.textContent === correctTarget) b.classList.add("correct"); });
        }
    } else {
        loadNextQuestion();
    }
};

// MATCH REJIMI
let matchSelections = [];
let matchesFound = 0;

function loadMatchMode() {
    matchGrid.innerHTML = "";
    matchSelections = [];
    matchesFound = 0;
    progressBar.style.width = "0%";

    const pool = (selectedUnitKey && database[selectedUnitKey]) ? database[selectedUnitKey] : activeWords;
    if (!pool || pool.length === 0) { alert('Match uchun yetarli so\'zlar topilmadi'); return; }
    const combined = shuffle([...pool]).slice(0, 10);
    matchWordsGlobal = combined;

    let uzWords = combined.map((w, idx) => ({ text: w.uz, id: idx, type: 'uz' }));
    let enWords = combined.map((w, idx) => ({ text: w.en, id: idx, type: 'en' }));

    uzWords = shuffle(uzWords);
    enWords = shuffle(enWords);

    for (let i = 0; i < combined.length; i++) {
        const btnUz = document.createElement("button");
        btnUz.className = "match-card";
        btnUz.textContent = uzWords[i].text;
        btnUz.onclick = () => handleMatchClick(btnUz, uzWords[i]);
        matchGrid.appendChild(btnUz);

        const btnEn = document.createElement("button");
        btnEn.className = "match-card";
        btnEn.textContent = enWords[i].text;
        btnEn.onclick = () => handleMatchClick(btnEn, enWords[i]);
        matchGrid.appendChild(btnEn);
    }
}

function handleMatchClick(btn, t) {
    if (btn.classList.contains("selected") || btn.classList.contains("matched")) return;
    btn.classList.add("selected");
    matchSelections.push({ btn, t });

    if (matchSelections.length === 2) {
        const [first, second] = matchSelections;
        matchGrid.style.pointerEvents = "none";

        if (first.t.id === second.t.id && first.t.type !== second.t.type) {
            setTimeout(() => {
                first.btn.classList.replace("selected", "matched");
                second.btn.classList.replace("selected", "matched");
                matchGrid.style.pointerEvents = "auto";
                matchesFound++;
                progressBar.style.width = `${(matchesFound / 10) * 100}%`;

                if (matchesFound === 10) {
                    setTimeout(showResults, 800);
                }
            }, 300);
        } else {
            mistakesCount++;

            // MATCH REJIMIDA ADASHILGAN SO'ZLARNI HAM RO'YXATGA QO'SHISH
            const w1 = matchWordsGlobal[first.t.id];
            const w2 = matchWordsGlobal[second.t.id];
            if (w1 && !failedWords.some(w => w.en === w1.en)) failedWords.push(w1);
            if (w2 && !failedWords.some(w => w.en === w2.en)) failedWords.push(w2);

            first.btn.classList.add("wrong", "shake");
            second.btn.classList.add("wrong", "shake");
            appContainer.classList.add("shake");
            setTimeout(() => {
                first.btn.classList.remove("selected", "wrong", "shake");
                second.btn.classList.remove("selected", "wrong", "shake");
                appContainer.classList.remove("shake");
                matchGrid.style.pointerEvents = "auto";
            }, 600);
        }
        matchSelections = [];
    }
}

